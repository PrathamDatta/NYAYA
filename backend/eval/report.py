"""Render docs/EVALUATION.md from eval/results/latest.json so every number in the document is a measured one.

    python -m eval.report [eval/results/latest.json] [../docs/EVALUATION.md]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "eval/results/latest.json")
    dst = Path(sys.argv[2] if len(sys.argv) > 2 else "../docs/EVALUATION.md")
    r = json.loads(src.read_text())
    L: list[str] = ["# Evaluation of the Law-AI models and the RAG pipeline", "",
                    f"_Generated by `eval/report.py` from `backend/eval/results/latest.json` ({r.get('generated_at', '?')[:19]} UTC). Re-run: `cd backend && python -m eval.run_eval all && python -m eval.report`._", "",
                    "**Read this first.** All numbers below were measured on this build's data on a CPU-only machine. The retrieval gold labels are *weak supervision* "
                    "derived from Supreme Court Reports headnotes, not expert relevance judgments, the corpus is a small sample of Supreme Court judgments, and **no statutes were ingested**. "
                    "Results therefore speak to *case-law passage retrieval on this sample* and must not be extrapolated to statute retrieval or to real user questions. "
                    "Confidence intervals are 95% bootstrap intervals over queries.", ""]
    if "retrieval" in r:
        x = r["retrieval"]
        L += ["## 1. Retrieval (headnote proposition → cited judgment paragraph)", "",
              f"{x['n_queries']} queries from {x['n_judgments']} judgments; candidate pool {x['candidate_chunks']} paragraph chunks (headnote chunks removed to prevent leakage). {x['note']}", ""]
        rows = []
        for name, m in x["results"].items():
            rows.append([name, m["P@5"], m["R@5"], m["R@10"], f"{m['R@10_ci95'][0]}–{m['R@10_ci95'][1]}", m["MRR"], f"{m['MRR_ci95'][0]}–{m['MRR_ci95'][1]}", m["nDCG@10"], m["judgment_hit@1"], m["judgment_hit@5"]])
        L += [table(["system", "P@5", "R@5", "R@10", "R@10 95% CI", "MRR", "MRR 95% CI", "nDCG@10", "judgment hit@1", "judgment hit@5"], rows), "",
              "`:raw` = L2-normalised mean-pooled vectors (the production setting); `:centred` = after subtracting the corpus mean (tested, did not help). Fusions use the raw vectors. `FUSION` rows use reciprocal-rank fusion (k=60).", ""]
        res = x["results"]
        dense = {k: v for k, v in res.items() if ":centred" in k and not k.startswith("FUSION")}
        best_dense = max(dense, key=lambda k: res[k]["MRR"])
        fus = {k: v for k, v in res.items() if k.startswith("FUSION")}
        best_fus = max(fus, key=lambda k: res[k]["MRR"])
        st = x.get("stratified")
        if st and st["low_overlap_max"] >= st["high_overlap_min"]:
            L += ["### How lexical is this benchmark?", "",
                  f"Mean overlap between a query's content words and its gold passage is **{st['overlap_mean']}**, and **{round(st['share_overlap_ge_0.95'] * 100)}%** of queries share ≥95% of their words with the gold passage "
                  "(headnote clauses largely restate the paragraph they summarise). Overlap is too uniform to split queries into meaningful low/high strata, so no stratified table is shown. "
                  "This strongly favours keyword matching and is the main reason BM25 looks so good here.", ""]
            st = None
        if st:
            lo, hi = st["low_overlap"], st["high_overlap"]
            n_lo, n_hi = next(iter(lo.values()))["n"], next(iter(hi.values()))["n"]
            L += ["### How lexical is this benchmark?", "",
                  f"Mean overlap between a query's content words and its gold passage is **{st['overlap_mean']}**, and **{round(st['share_overlap_ge_0.95'] * 100)}%** of queries share ≥95% of their words with the gold passage "
                  "(headnote clauses largely restate the paragraph they summarise). This strongly favours keyword matching and is the main reason BM25 looks so good here.", "",
                  "### Stratified by vocabulary overlap", "",
                  f"Lowest-overlap 40% of queries ({n_lo} queries, overlap ≤ {st['low_overlap_max']}) vs highest-overlap 40% ({n_hi} queries, overlap ≥ {st['high_overlap_min']}).", "",
                  table(["system", "MRR low-overlap", "R@10 low-overlap", "MRR high-overlap", "R@10 high-overlap"], [[k, lo[k]["MRR"], lo[k]["R@10"], hi[k]["MRR"], hi[k]["R@10"]] for k in lo]), ""]
        sr = x.get("stress_50pct_words_removed")
        if sr:
            L += ["### Stress test: 50% of each query's content words removed", "",
                  "A *synthetic* simulation of paraphrase/lay wording (random words deleted, fixed seed). It is not real user phrasing, but it shows which systems degrade gracefully when vocabulary no longer matches.", "",
                  table(["system", "MRR", "MRR 95% CI", "R@10", "judgment hit@5"], [[k, v["MRR"], f"{v['MRR_ci95'][0]}–{v['MRR_ci95'][1]}", v["R@10"], v["judgment_hit@5"]] for k, v in sr.items()]), ""]
        res = x["results"]
        dense = {k: v for k, v in res.items() if k.endswith(":raw")}
        best_dense = max(dense, key=lambda k: res[k]["MRR"])
        fus = {k: v for k, v in res.items() if k.startswith("FUSION")}
        best_fus = max(fus, key=lambda k: res[k]["MRR"])
        L += ["### Reading the tables", "",
              f"* Best single dense encoder by MRR (original queries): **{best_dense.split(':')[0]}** ({res[best_dense]['MRR']}); BM25 alone: {res['bm25']['MRR']}.",
              f"* Best fusion by MRR: **{best_fus.replace('FUSION ', '')}** ({res[best_fus]['MRR']}, CI {res[best_fus]['MRR_ci95'][0]}–{res[best_fus]['MRR_ci95'][1]}).",
              "* Overlapping confidence intervals mean a difference is **not** established by this sample.", ""]
    if "topic" in r:
        t = r["topic"]
        rows = [[k, v["accuracy"], f"{v['ci95'][0]}–{v['ci95'][1]}" if "ci95" in v else "—"] for k, v in t["results"].items()]
        L += ["## 2. Legal-topic identification", "", f"{t['n_queries']} hand-written synthetic questions across {t['n_topics']} topics (consumer, tenancy, contract, cyber fraud, criminal, family, employment, property); nearest-prototype classification, no training. Chance = {round(1 / t['n_topics'], 3)}.", "",
              table(["method", "accuracy", "95% CI"], rows), "",
              "`proto_centred` subtracts the mean of the eight topic-prototype vectors (needs no corpus or test data). Ensembles average per-encoder z-scored similarities.", ""]
    if "domain" in r:
        d = r["domain"]
        L += ["## 3. Legal-language detection (CustomInLawBERT's role)", "",
              f"Score = cosine between a question and the corpus centroid in each encoder's space. {d['n_legal']} lay legal questions vs {d['n_unrelated']} unrelated ones. AUC = probability a legal question outscores an unrelated one.", "",
              table(["encoder", "AUC", "AUC 95% CI", "best threshold", "balanced acc. at threshold", "mean legal", "mean unrelated"],
                    [[k, v["auc"], f"{v['auc_ci95'][0]}–{v['auc_ci95'][1]}", v["best_threshold"], v["balanced_accuracy_at_threshold"], v["legal_mean"], v["unrelated_mean"]] for k, v in d["results"].items()]), "",
              "The threshold is specific to this corpus and this encoder; re-run the evaluation after changing the corpus.", ""]
    if "gate" in r:
        g = r["gate"]
        rows = [[k, v["best"]["threshold"], v["best"]["headnote_kept"], v["best"]["doctrinal_kept"], v["best"]["unrelated_declined"], v["best"]["balanced_accuracy"], v["doctrinal_min"], v["unrelated_max"]] for k, v in g["rules"].items()]
        L += ["## 4. Evidence gate (when to decline)", "",
              f"Answerable: {g['n_headnote']} headnote clauses and {g['n_doctrinal']} hand-written short doctrinal questions (plausibly covered; **not lawyer-verified**). Unrelated: {g['n_unrelated']} clearly non-legal questions. "
              "Coverage = IDF-weighted share of question terms found in the retrieved passage(s); terms unknown to the corpus count against it.", "",
              table(["coverage definition", "best threshold", "headnote kept", "doctrinal kept", "unrelated declined", "balanced acc.", "doctrinal min", "unrelated max"], rows), "",
              "Where `doctrinal min` ≤ `unrelated max` no threshold separates the sets perfectly.", ""]
        pr = g["production_rule"]
        L += ["### The rule that ships", "",
              f"Decline unless the **best single passage covers ≥ {pr['min_query_coverage']}** of the question's IDF weight. Measured: headnote questions kept **{pr['headnote_kept']}**, doctrinal kept **{pr['doctrinal_kept']}**, unrelated declined **{pr['unrelated_declined']}**.", ""]
        if pr["doctrinal_declined"]:
            L += ["Doctrinal questions that are **wrongly declined**: " + "; ".join(f"“{q}”" for q in pr["doctrinal_declined"]), ""]
        if pr["unrelated_still_answered"]:
            L += ["Unrelated questions that **still get answered**: " + "; ".join(f"“{q}”" for q in pr["unrelated_still_answered"]), ""]
        L += ["### Why the legal-language detector is advisory, not a gate", "",
              f"Used as a hard condition (CustomInLawBERT score ≥ {pr['domain_threshold']}) it would have rejected **{round(pr['legal_language_detector_rejects_doctrinal'] * 100)}%** of the doctrinal questions and "
              f"{round(pr['legal_language_detector_rejects_headnote'] * 100)}% of headnote clauses while catching {round(pr['legal_language_detector_catches_unrelated'] * 100)}% of unrelated ones. "
              "It was calibrated on lay narratives, and short doctrinal questions score lower. So it only chooses the wording of a decline.", "",
              "Caveat: near-domain questions the corpus simply lacks (e.g. tenancy law when no tenancy statute is ingested) are a harder case that these sets do not measure.", ""]
    if "pipeline" in r:
        p = r["pipeline"]
        L += ["## 5. End-to-end pipeline", "", f"{p['n_queries']} questions, warm models, CPU. Outcomes: {p['status']}. Mean citation validity **{p['mean_citation_validity']}** "
              f"({p['answers_with_invalid_citation']} answers with any invalid citation), {p['mean_citations_per_answer']} citations per answer.", "",
              table(["latency", "seconds"], [[k, v] for k, v in p["latency_s"].items()] + [[f"mean {k}", v] for k, v in p["stage_mean_s"].items()]), "", f"_{p['note']}_", ""]
    if "translation" in r:
        t = r["translation"]
        L += ["## 6. Translation (InLegalTrans-En2Indic-1B)", "", f"_{t['note']}_", "",
              table(["language", "s / sentence", "share of letters in target script", "output/input length ratio"], [[k, v["mean_s_per_sentence"], v["target_script_share"], v["len_ratio"]] for k, v in t["languages"].items()]), "",
              ""]
    if "resources" in r:
        s = r["resources"]
        rows = [[k, v.get("load_plus_first_encode_s", v.get("load_plus_first_translation_s")), v["peak_rss_mb"], v.get("steady_rss_mb", "—"),
                 v.get("s_per_passage_warm", v.get("s_per_sentence_warm", "—"))] for k, v in s.items() if isinstance(v, dict) and "peak_rss_mb" in v]
        L += ["## 7. Resources (fresh process per model)", "", table(["model", "load + first call (s)", "peak RSS (MB)", "steady RSS (MB)", "warm s per passage / sentence"], rows), "",
              f"Model cache on disk: {s['disk_mb_models_dir']} MB. Host: {s['host']}. GPU: none available in this build; CUDA path untested.", ""]
    dst.write_text("\n".join(L) + "\n")
    print("wrote", dst)


if __name__ == "__main__":
    main()
